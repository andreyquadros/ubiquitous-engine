fn main() {
    let root = workspace_root();
    stamp("UBIQX_BUILD_EPOCH", "0", || {
        git(&root, &["log", "-1", "--format=%ct"])
    });
    stamp("UBIQX_BUILD_NUMBER", "0", || {
        git(&root, &["rev-list", "--count", "HEAD"])
    });
    stamp("UBIQX_BUILD_SHA", "dev", || {
        git(&root, &["rev-parse", "--short=7", "HEAD"])
    });
    stamp("UBIQX_BUILD_BRANCH", "", || {
        git(&root, &["rev-parse", "--abbrev-ref", "HEAD"]).filter(|b| b != "HEAD")
    });
    stamp("UBIQX_UPDATE_FEED_URL", DEFAULT_FEED_URL, || None);

    // A new commit changes the stamp of a local build: watch the files git moves then
    // (asked from git, since `.git` is a file in a worktree).
    if let Some(git_dir) = git(&root, &["rev-parse", "--absolute-git-dir"]).map(PathBuf::from) {
        println!("cargo:rerun-if-changed={}", git_dir.join("HEAD").display());
        if let Some(head) = std::fs::read_to_string(git_dir.join("HEAD"))
            .ok()
            .and_then(|h| h.trim().strip_prefix("ref: ").map(str::to_string))
        {
            println!("cargo:rerun-if-changed={}", git_dir.join(head).display());
        }
    }

    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(app_manifest()))
        .expect("tauri build steps");
}

/// The permission a capability names to allow `command`: `allow-` and the command in kebab
/// case, as Tauri derives it, with the module's source name replaced by the machine one
/// (design 0.1: capability files never carry the source name).
fn permission(command: &str) -> String {
    format!(
        "allow-{}",
        command.replace("nofap", "shield").replace('_', "-")
    )
}

/// The app's permission manifest: one permission per command of [`COMMANDS`], written to
/// `OUT_DIR`. `AppManifest::commands` would write the same permissions into the source tree
/// (`permissions/autogenerated/<command>.toml`, named after the command) and name them
/// after the command in the capability files; this keeps both in the build output.
fn app_manifest() -> tauri_build::AppManifest {
    let dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("app-permissions");
    std::fs::create_dir_all(&dir).expect("app permissions directory");
    let mut toml = String::from("# Generated by build.rs from COMMANDS.\n");
    for command in COMMANDS {
        let identifier = permission(command);
        toml.push_str(&format!(
            "\n[[permission]]\nidentifier = \"{identifier}\"\n"
        ));
        toml.push_str(&format!(
            "description = \"Allows the {command} command.\"\n"
        ));
        toml.push_str(&format!("commands.allow = [\"{command}\"]\n"));
    }
    let file = dir.join("commands.toml");
    // Written only when it changes, so a rebuild does not touch it for nothing.
    if std::fs::read_to_string(&file).ok().as_deref() != Some(toml.as_str()) {
        std::fs::write(&file, toml).expect("app permissions file");
    }
    let pattern = dir.join("*.toml").to_string_lossy().into_owned();
    tauri_build::AppManifest::new().permissions_path_pattern(Box::leak(pattern.into_boxed_str()))
}

/// Emits `cargo:rustc-env=NAME=value`, taking the value from the environment variable of
/// the same name when set (CI), from `fallback()` otherwise, and `default` as a last resort.
fn stamp(name: &str, default: &str, fallback: impl FnOnce() -> Option<String>) {
    println!("cargo:rerun-if-env-changed={name}");
    let value = std::env::var(name)
        .ok()
        .map(|v| v.trim().to_string())
        .filter(|v| !v.is_empty())
        .or_else(fallback)
        .unwrap_or_else(|| default.to_string());
    println!("cargo:rustc-env={name}={value}");
}

fn git(root: &Path, args: &[&str]) -> Option<String> {
    let out = Command::new("git")
        .arg("-C")
        .arg(root)
        .args(args)
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    let s = String::from_utf8(out.stdout).ok()?.trim().to_string();
    (!s.is_empty()).then_some(s)
}

/// `apps/desktop/src-tauri` → the workspace root, where `.git` lives.
fn workspace_root() -> PathBuf {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    manifest
        .ancestors()
        .nth(3)
        .map(Path::to_path_buf)
        .unwrap_or(manifest)
}
